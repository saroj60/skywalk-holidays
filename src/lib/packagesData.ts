    // Map outlineItinerary or detailed itinerary to unified format
    const itinerary = (pkg.itinerary || pkg.outlineItinerary || []).map((day: any) => ({
      day: day.day || "Day",
      title: day.title || "",
      highlight: day.highlight || "",
      description: day.desc || day.description || day.activity || "",
      meals: day.meals || "",
      stay: day.stay || "",
    }));

    // Inclusions & Exclusions
    const inclusions = pkg.inclusions || [];
    const exclusions = pkg.exclusions || [];
    const highlights = pkg.highlights || [];

    // Gallery images
    const gallery = (pkg.gallery || []).map((g: any) => typeof g === "string" ? g : (g.url || "")).filter(Boolean);
    const coverImage = pkg.image || pkg.coverImage || gallery[0] || "/images/bangkok-pattaya.png";

    // Hotel & transport info
    let hotelInfo = "3-Star Deluxe Hotels with Daily Breakfast";
    if (typeof pkg.hotelInfo === "string") {
      hotelInfo = pkg.hotelInfo;
    } else if (pkg.hotelInfo && typeof pkg.hotelInfo === "object") {
      hotelInfo = `${pkg.hotelInfo.name || "Deluxe Partner Hotels"} (${pkg.hotelInfo.rating || "3-Star Deluxe"})`;
    }

